#!/usr/bin/env python3
"""Render a Lab3 floorplan as a TikZ picture (Python 3.10 stdlib only).

    python3 tools/plot_tikz.py <input> <output> <out.tex> [--nets] [--width F]

Writes a single `tikzpicture` environment that can be \\input into a LaTeX
document (used for the student spec, since xelatex cannot include SVG).
The picture is scaled so that the outline is F*\\textwidth wide (default 0.6).

Drawn: the outline with its dimensions, blocks filled by kind (soft /
fixed-shape / preplaced; preplaced blocks are hatched), block names, MIB
groups as a dashed outline in a shared group colour, boundary constraints as
thick bars on the required block edges (solid when
satisfied, dashed when not), terminals as dots with names, and
optionally (--nets) connections as thin lines between centroids with their
weights.

Requirements on the including document: \\usepackage{tikz} (xcolor is loaded
by tikz). No TikZ libraries are needed; hatching is done with \\clip.
The output file is read leniently so infeasible outputs can be drawn too.
"""

import argparse
import sys

KIND_FILL = {"SOFT": "9ECAE1", "FIXED": "FDAE6B", "PREPLACED": "D9D9D9"}
MIB_COLORS = ["7B3294", "008837", "E66101", "0571B0", "CA0020", "5E3C99",
              "1B7837", "B35806", "2166AC", "D6604D", "542788", "01665E"]
BOUND_COLOR = "C51B7D"


def parse_input(path):
    with open(path) as f:
        tok = f.read().split()
    pos = 0

    def nxt():
        nonlocal pos
        if pos >= len(tok):
            raise ValueError("unexpected end of input file")
        pos += 1
        return tok[pos - 1]

    def kw(k):
        t = nxt()
        if t != k:
            raise ValueError(f"expected {k!r}, got {t!r}")

    inst = {"blocks": {}, "order": [], "terminals": {}, "conns": [],
            "mibs": [], "bounds": {}}
    kw("OUTLINE")
    inst["W"], inst["H"] = int(nxt()), int(nxt())
    kw("WLTHRESHOLD")
    inst["T"] = nxt()
    kw("ASPECTRATIO")
    inst["R"] = int(nxt())
    kw("BLOCKS")
    for _ in range(int(nxt())):
        kind, name = nxt(), nxt()
        b = {"kind": kind}
        if kind == "SOFT":
            b["area"] = int(nxt())
        elif kind in ("FIXED", "PREPLACED"):
            b["w"], b["h"] = int(nxt()), int(nxt())
            if kind == "PREPLACED":
                b["x"], b["y"] = int(nxt()), int(nxt())
        else:
            raise ValueError(f"unknown block kind {kind!r}")
        inst["blocks"][name] = b
        inst["order"].append(name)
    kw("TERMINALS")
    for _ in range(int(nxt())):
        kw("TERMINAL")
        name = nxt()
        inst["terminals"][name] = (int(nxt()), int(nxt()))
    kw("CONNECTIONS")
    for _ in range(int(nxt())):
        kw("CONN")
        inst["conns"].append((nxt(), nxt(), int(nxt())))
    kw("MIBS")
    for _ in range(int(nxt())):
        kw("MIB")
        k = int(nxt())
        inst["mibs"].append([nxt() for _ in range(k)])
    kw("BOUNDARIES")
    edges = {"LEFT", "RIGHT", "TOP", "BOTTOM"}
    for _ in range(int(nxt())):
        kw("BOUNDARY")
        name = nxt()
        es = [nxt()]
        if pos < len(tok) and tok[pos] in edges:
            es.append(nxt())
        inst["bounds"][name] = es
    return inst


def parse_output(path, inst):
    rects = {}
    with open(path) as f:
        lines = [ln.split() for ln in f]
    for i, t in enumerate(lines, 1):
        if not t or (t[0] in ("WIRELENGTH", "BLOCKS") and len(t) == 2):
            continue
        if len(t) == 5 and t[0] in inst["blocks"]:
            try:
                rects[t[0]] = tuple(int(v) for v in t[1:])
                continue
            except ValueError:
                pass
        print(f"plot_tikz.py: warning: skipping output line {i}: "
              f"{' '.join(t)}", file=sys.stderr)
    return rects


def tex_escape(s):
    out = []
    for ch in s:
        if ch in "#$%&_{}":
            out.append("\\" + ch)
        elif ch == "\\":
            out.append("\\textbackslash{}")
        elif ch == "^":
            out.append("\\^{}")
        elif ch == "~":
            out.append("\\~{}")
        else:
            out.append(ch)
    return "".join(out)


def fmt(v):
    """Number for a TikZ coordinate: integer if whole, else one decimal."""
    return str(int(v)) if float(v).is_integer() else f"{v:.1f}"


def render(inst, rects, show_nets, width_frac):
    W, H = inst["W"], inst["H"]
    n = len(inst["order"])
    # Outline width = width_frac*\textwidth; keep tall outlines bounded.
    s = width_frac / W
    if H * s > 1.2 * width_frac:
        s = 1.2 * width_frac / H
    if n <= 20:
        name_font = "\\footnotesize"
    elif n <= 60:
        name_font = "\\tiny"
    else:
        name_font = None

    o = []
    o.append("% Generated by tools/plot_tikz.py -- do not edit by hand.")
    o.append("% Needs \\usepackage{tikz}; no TikZ libraries required.")
    o.append(f"\\begin{{tikzpicture}}[x={s:.6g}\\textwidth,"
             f"y={s:.6g}\\textwidth,font=\\sffamily]")
    for k, c in KIND_FILL.items():
        o.append(f"\\definecolor{{lab3{k.lower()}}}{{HTML}}{{{c}}}")
    for i, c in enumerate(MIB_COLORS):
        o.append(f"\\definecolor{{lab3mib{i}}}{{HTML}}{{{c}}}")
    o.append(f"\\definecolor{{lab3bound}}{{HTML}}{{{BOUND_COLOR}}}")

    # Outline.
    o.append(f"\\fill[white] (0,0) rectangle ({W},{H});")

    # Blocks.
    hatch_step = max(W, H) / 40.0
    for name in inst["order"]:
        if name not in rects:
            continue
        x, y, w, h = rects[name]
        kind = inst["blocks"][name]["kind"]
        col = f"lab3{kind.lower()}"
        o.append(f"\\filldraw[fill={col},draw=black!70,line width=0.4pt] "
                 f"({x},{y}) rectangle ({x + w},{y + h});")
        if kind == "PREPLACED":
            o.append("\\begin{scope}")
            o.append(f"\\clip ({x},{y}) rectangle ({x + w},{y + h});")
            # 45-degree lines covering the block.
            t = -h
            while t < w:
                o.append(f"\\draw[black!45,line width=0.3pt] "
                         f"({fmt(x + t)},{y}) -- ({fmt(x + t + h)},{y + h});")
                t += hatch_step
            o.append("\\end{scope}")

    # MIB groups: dashed outline per member in the group colour.
    for gi, grp in enumerate(inst["mibs"]):
        col = f"lab3mib{gi % len(MIB_COLORS)}"
        inset = min(W, H) / 120.0
        for name in grp:
            if name not in rects:
                continue
            x, y, w, h = rects[name]
            o.append(f"\\draw[{col},dashed,line width=1.2pt] "
                     f"({fmt(x + inset)},{fmt(y + inset)}) rectangle "
                     f"({fmt(x + w - inset)},{fmt(y + h - inset)});")

    # Connections.
    def point(name):
        if name in inst["terminals"]:
            return inst["terminals"][name]
        if name in rects:
            x, y, w, h = rects[name]
            return (x + w / 2.0, y + h / 2.0)
        return None

    if show_nets:
        for a, b, c in inst["conns"]:
            pa, pb = point(a), point(b)
            if pa is None or pb is None:
                continue
            o.append(f"\\draw[black!60,line width=0.5pt] "
                     f"({fmt(pa[0])},{fmt(pa[1])}) -- "
                     f"node[fill=white,inner sep=0.8pt,font=\\sffamily\\tiny]"
                     f" {{{c}}} ({fmt(pb[0])},{fmt(pb[1])});")

    # Block names (drawn after nets so they stay readable).
    if name_font:
        for name in inst["order"]:
            if name not in rects:
                continue
            x, y, w, h = rects[name]
            o.append(f"\\node[font=\\sffamily{name_font}\\bfseries,"
                     f"fill=white,fill opacity=0.75,text opacity=1,"
                     f"inner sep=1pt,above] at ({fmt(x + w / 2)},"
                     f"{fmt(y + h / 2)}) {{{tex_escape(name)}}};")

    # Outline border on top.
    o.append(f"\\draw[black,line width=1.2pt] (0,0) rectangle ({W},{H});")

    # Boundary constraints: thick bar on each required block edge, drawn
    # just inside the block so it stays visible next to the outline border.
    # A bar is solid when the block touches that outline edge, dashed if not.
    for name, es in inst["bounds"].items():
        if name not in rects:
            continue
        x, y, w, h = rects[name]
        seg = {"LEFT": ((x, y), (x, y + h), "xshift=1.3pt", x == 0),
               "RIGHT": ((x + w, y), (x + w, y + h), "xshift=-1.3pt",
                         x + w == W),
               "BOTTOM": ((x, y), (x + w, y), "yshift=1.3pt", y == 0),
               "TOP": ((x, y + h), (x + w, y + h), "yshift=-1.3pt",
                       y + h == H)}
        for e in es:
            (ax, ay), (bx, by), shift, ok = seg[e]
            style = "" if ok else ",dash pattern=on 4pt off 2pt"
            o.append(f"\\draw[lab3bound,line width=2.4pt,line cap=butt"
                     f"{style}] ([{shift}]{ax},{ay}) -- ([{shift}]{bx},{by});")

    # Terminals.
    for name, (tx, ty) in inst["terminals"].items():
        if tx == 0:
            anchor = "east"
        elif tx == W:
            anchor = "west"
        elif ty == 0:
            anchor = "north"
        else:
            anchor = "south"
        o.append(f"\\fill[black] ({tx},{ty}) circle (2.2pt);")
        o.append(f"\\node[anchor={anchor},font=\\sffamily\\footnotesize,"
                 f"inner sep=3pt] at ({tx},{ty}) {{{tex_escape(name)}}};")

    # Dimensions: width below, height to the left (absolute offsets).
    o.append(f"\\draw[black!70,<->,>=stealth] ([yshift=-7mm]0,0) -- "
             f"node[fill=white,inner sep=1pt,font=\\sffamily\\footnotesize] "
             f"{{$W={W}$}} ([yshift=-7mm]{W},0);")
    for xx in (0, W):
        o.append(f"\\draw[black!40] ([yshift=-1mm]{xx},0) -- "
                 f"([yshift=-8mm]{xx},0);")
    o.append(f"\\draw[black!70,<->,>=stealth] ([xshift=-11mm]0,0) -- "
             f"node[fill=white,inner sep=1pt,font=\\sffamily\\footnotesize,"
             f"rotate=90] {{$H={H}$}} ([xshift=-11mm]0,{H});")
    for yy in (0, H):
        o.append(f"\\draw[black!40] ([xshift=-1mm]0,{yy}) -- "
                 f"([xshift=-12mm]0,{yy});")
    o.append(f"\\node[anchor=north east,font=\\sffamily\\footnotesize,"
             f"inner sep=1pt] at ([xshift=-1mm,yshift=-1mm]0,0) {{$(0,0)$}};")
    o.append("\\end{tikzpicture}")
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("input")
    ap.add_argument("output")
    ap.add_argument("tex")
    ap.add_argument("--nets", action="store_true",
                    help="draw connections between centroids with weights")
    ap.add_argument("--width", type=float, default=0.6,
                    help="outline width as a fraction of \\textwidth")
    args = ap.parse_args()
    try:
        inst = parse_input(args.input)
    except (OSError, ValueError) as e:
        sys.exit(f"plot_tikz.py: {args.input}: {e}")
    try:
        rects = parse_output(args.output, inst)
    except OSError as e:
        sys.exit(f"plot_tikz.py: {args.output}: {e}")
    missing = [b for b in inst["order"] if b not in rects]
    if missing:
        print(f"plot_tikz.py: warning: {len(missing)} block(s) missing from "
              f"output, not drawn", file=sys.stderr)
    with open(args.tex, "w") as f:
        f.write(render(inst, rects, args.nets, args.width))


if __name__ == "__main__":
    main()
